import 'dart:convert';
import 'dart:io';

void main() {
  // Resolve the script location to find package roots relative to it
  final scriptPath = File(
    Platform.script.toFilePath(),
  ).resolveSymbolicLinksSync();
  final pathSeparator = Platform.pathSeparator;

  // scriptPath is: .../packages/steward_cli/tool/sync_versions.dart
  // dirname of scriptPath is .../packages/steward_cli/tool
  final toolDirPath = scriptPath.substring(
    0,
    scriptPath.lastIndexOf(pathSeparator),
  );
  // dirname of toolDir is .../packages/steward_cli
  final stewardCliDirPath = toolDirPath.substring(
    0,
    toolDirPath.lastIndexOf(pathSeparator),
  );
  // dirname of stewardCliDir is .../packages
  final packagesDirPath = stewardCliDirPath.substring(
    0,
    stewardCliDirPath.lastIndexOf(pathSeparator),
  );
  // dirname of packages is ... (root)
  final rootDirPath = packagesDirPath.substring(
    0,
    packagesDirPath.lastIndexOf(pathSeparator),
  );

  final pkgFile = File('$rootDirPath${pathSeparator}package.json');
  final pubspecFile = File('$stewardCliDirPath${pathSeparator}pubspec.yaml');

  if (!pkgFile.existsSync()) {
    stderr.writeln('Error: package.json not found at ${pkgFile.path}');
    exit(1);
  }

  if (!pubspecFile.existsSync()) {
    stderr.writeln('Error: pubspec.yaml not found at ${pubspecFile.path}');
    exit(1);
  }

  final pkgJson =
      jsonDecode(pkgFile.readAsStringSync()) as Map<String, dynamic>;
  final version = pkgJson['version'] as String?;

  if (version == null) {
    stderr.writeln('Error: No version found in package.json');
    exit(1);
  }

  var pubspec = pubspecFile.readAsStringSync();
  final versionRegex = RegExp(r'^version:\s*[^\r\n]+', multiLine: true);

  if (!versionRegex.hasMatch(pubspec)) {
    stderr.writeln('Error: Could not find version line in pubspec.yaml');
    exit(1);
  }

  pubspec = pubspec.replaceFirst(versionRegex, 'version: $version');
  pubspecFile.writeAsStringSync(pubspec);

  File(
    '$stewardCliDirPath${pathSeparator}lib${pathSeparator}src${pathSeparator}steward_version.dart',
  ).writeAsStringSync(
    '''
// Generated by packages/steward_cli/tool/sync_versions.dart — do not edit by hand.
const stewardPackageVersion = '$version';
''',
  );

  final serverJsonFile = File(
    '$stewardCliDirPath${pathSeparator}server.json',
  );
  if (serverJsonFile.existsSync()) {
    final serverJson =
        jsonDecode(serverJsonFile.readAsStringSync()) as Map<String, dynamic>;
    serverJson['version'] = version;
    final packages = serverJson['packages'];
    if (packages is List) {
      for (final item in packages) {
        if (item is! Map) continue;
        if (item['registryType'] == 'oci' && item['identifier'] is String) {
          final id = item['identifier'] as String;
          final colon = id.lastIndexOf(':');
          if (colon > 0) {
            item['identifier'] = '${id.substring(0, colon + 1)}$version';
          }
        }
      }
    }
    const encoder = JsonEncoder.withIndent('  ');
    serverJsonFile.writeAsStringSync('${encoder.convert(serverJson)}\n');
  }

  stdout.writeln(
    'Synced version: pubspec.yaml, steward_version.dart, and server.json are now at $version',
  );
}
